const aliases = {
    "en-us": "en",
    "en-gb": "en",
    "es-es": "es",
    "es-mx": "es",
    "pt-br": "pt",
    "pt-pt": "pt",
    cz: "cs",
};

export const supportedLocales = [
    { code: "en", labelKey: "languageEnglish" },
    { code: "es", labelKey: "languageSpanish" },
    { code: "fr", labelKey: "languageFrench" },
    { code: "de", labelKey: "languageGerman" },
    { code: "pt", labelKey: "languagePortuguese" },
    { code: "it", labelKey: "languageItalian" },
    { code: "nl", labelKey: "languageDutch" },
    { code: "pl", labelKey: "languagePolish" },
];

export function normalizeLocale(locale) {
    const code = String(locale || "en")
        .toLowerCase()
        .replace("_", "-");
    const normalized = aliases[code] || code.split("-")[0];
    return translations[normalized] ? normalized : "en";
}

export function createTranslator(locale) {
    const normalized = normalizeLocale(locale);
    const messages = translations[normalized] || base;
    return (key, params = {}) => {
        const template = messages[key] || base[key] || key;
        return template.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? `{${name}}`).toString());
    };
}
